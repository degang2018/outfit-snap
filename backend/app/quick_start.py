def _encode(path: str) -> tuple[str, str] | None:
    """把本地图片缩到 MAX_EDGE 并转成 base64 JPEG(只支持 jpeg/png/gif/webp,统一成 jpeg)。"""
    try:
        from PIL import Image

        img = Image.open(path).convert("RGB")
        img.thumbnail((MAX_EDGE, MAX_EDGE))
        buf = io.BytesIO()
        img.save(buf, "JPEG", quality=VISION_JPEG_QUALITY)
        return base64.b64encode(buf.getvalue()).decode(), "image/jpeg"
    except Exception:  # noqa: BLE001
        return None


def _encode_all(paths: list[str]) -> list[tuple[str, str]] | None:
    """把每张图都缩到 MAX_EDGE 再 base64;有一张读不了就整体失败。"""
    out: list[tuple[str, str]] = []
    for p in paths:
        one = _encode(p)
        if one is None:
            return None
        out.append(one)
    return out


# 商品图 / 模特图上的**拍摄属性**词。它们是"这张图怎么拍的",不是这件衣服的设计 ——
# 一旦进了视频提示词,模型就会照着把衣服画成半透明(实测:平铺的蕾丝上衣被画成一层透明的纱,
# 隔着还能看见里面的小雏菊上衣和身体)。所以描述里出现这类词一律清掉。
# 顺序要紧:先长后短(「半透明」要在「透明」之前处理,否则会剩下个「半」)。
_TRANSPARENT_WORDS = (
    "隐约见底",
    "隐约透",
    "薄如蝉翼",
    "半透明",
    "微透",
    "薄透",
    "薄纱",
    "透视",
    "透明",
)


def sanitize_desc(text: str | None) -> str:
    """清掉描述里的"透"类拍摄属性词,并把因此留下的多余标点收干净。"""
    s = str(text or "")
    for w in _TRANSPARENT_WORDS:
        s = s.replace(w, "")
    s = re.sub(r"[，,、]{2,}", "，", s)
    s = re.sub(r"[（(]\s*[）)]", "", s)
    return s.strip(" ，,、;；()（）")


