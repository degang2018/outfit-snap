def _replace_group(name: str, slot: str = "") -> str:
    """这一件和谁互相替换(body / outer / bottom / whole / other)。"""
    place, outside = parse_slot(slot)
    if place == "全身":
        return "whole"
    if place == "上身":
        return "outer" if outside else "body"
    if place == "下身":
        return "bottom"
    if place == "脚":
        return "feet"
    if place:  # 头 / 手 / 配饰:小件,谁都不顶
        return "other"
    n = _strip_piece_prefix(name)
    for g, keys in _REPLACE_HINTS:
        if any(k in n for k in keys):
            return g
    return "other"


def _displaced_groups(name: str, slot: str = "", close: str = "") -> set[str]:
    """这一件穿上身之后,打底里**哪几组**会被顶掉。

    整身(连衣裙 / 连体衣)是唯一的例外:它一件盖住上下半身,穿上之后打底的上装和裤 / 裙
    **两组都要消失**(实测漏过:只顶掉睡裤,状态展示镜写成"睡衣上衣 + 连衣裙")。

    外套默认只是「加穿」,谁都不顶;但**扣上的外套**(close == "closed")已经是这一镜的新上衣,
    里面那件旧上衣就该退场 —— 否则提示词会同时要求"开衫扣齐、不许露出里面的衣服"和
    "睡衣上衣一件都不消失",模型只能演成敞怀露睡衣(项目 tezsd99 第 4 / 5 镜就是这么翻的)。
    """
    rg = _replace_group(name, slot)
    if rg == "whole":
        return {"body", "bottom", "whole"}
    if rg == "outer":
        return (
            {"outer", "body"}
            if str(close or "").strip().lower() == "closed"
            else {"outer"}
        )
    return {rg} if rg != "other" else set()


def _entry_spot(group: str, k: int) -> str:
    """这一件从画面哪里进场 —— **按它要换的部位定高度**。

    下装不能从画面上角进来(实测裤子被放到她头顶高度飘),要从侧边、和她腰胯齐高的位置进;
    鞋从下方、帽子从上方。上衣左右交替。
    """
    if group == "bottom":
        return "画面右侧、大约和她腰胯齐高的位置"
    if group == "feet":
        return "画面右下方"
    if group == "head":
        return "画面上方"
    if group == "hand":
        return "画面右侧、大约和她胸口齐高的位置"
    return "画面右上方" if k % 2 == 1 else "画面左上方"


def _is_skirt(name: str) -> bool:
    return "裙" in (name or "")


def float_change_sequence_text(
    pieces, bases=None, lang: str = "zh", accessories=None
) -> str:
    """一镜要换好几件时的通用换装说明。

    文案**照抄「实测能出好结果」的那一版**(项目 #92 的 566),只把三处换成按件名推出来:
    第几件是哪件、这一件移到身上哪个部位(_piece_part)、从哪个角落进场(按部位定高度),
    以及**这一件顶掉的是身上哪件旧件**(按部位从 bases 里配 —— 裙配睡裤、上衣配睡衣上衣;
    配不到就写"直接加穿")。

    件数变了 / 以后加一件棉帽,这里自动多出一拍,规则句一个字都不用改。
    """
    names = [
        str(p.get("name") or "").strip()
        for p in (pieces or [])
        if str(p.get("name") or "").strip()
    ]
    if not names:
        return ""
    # 件名(兜底) + 读图给的部位,两条并列、下标对齐
    slots = [_slot_of(p) for p in (pieces or []) if str(p.get("name") or "").strip()]
    order = sorted(
        range(len(names)), key=lambda i: (_wear_layer(names[i], slots[i]), i)
    )
    base_slots = {str(b.get("name") or "").strip(): _slot_of(b) for b in (bases or [])}
    base_names = [
        str(b.get("name") or "").strip()
        for b in (bases or [])
        if str(b.get("name") or "").strip()
    ]
    beats: list[str] = []
    used_old: set[str] = set()  # 一件旧件只能被「换掉」一次,用掉就不再参与配对
