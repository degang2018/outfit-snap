def whole_look_action(base_names, new_names) -> str:
    """「单镜整套 · 衣服飘入替换」这一镜的动作说明(一镜里换整套)。

    **刻意避开 CHANGE_MARKERS 里的词**("平移进来" / "吸到她身上" / "从画面上方落下"…):
    带上那些词,这一镜就会被当成「按件数自动放大帧数 + 拼时间轴」的换装镜(见
    routers/projects.py),而整套一镜演完的时长是定好的、不该被自动改掉。

    **只写「机位 + 她站着不动」这一层**:"她要换哪几件、一件一件怎么飞进来"全部交给
    float_change_sequence_text 逐件写 —— 这里再写一遍反而会跟逐件说明抢话、把节奏说乱
    (实测:开头单独强调一句"这件衣服一件件飘进来"之后,模型把中间的旧件消失漏掉了)。

    句中的「固定的全景全身构图」是**给 script_split 认的标记**(WHOLE_LOOK_ACTION_MARK):
    带上它,这一镜的尾部就改用 566 那一版(固定全身 + 锁死人物大小)。
    """
    return (
        "已经穿好完整套装,固定机位、固定的全景全身构图,她站在纯白背景正中央、"
        "双脚钉在同一个点不动、脸朝镜头。"
    )


# 这一镜的场景描述:照抄 566 那版(不要用白棚预设的长描述)。
# 末尾这个句号是**故意**的:566 那份提示词里是「…商业棚拍光线。。」两个句号
# (描述本身以。结尾、模板又补一个。)。要和那一版逐字一致,这里就得带着它 —— 别顺手删掉。
WHOLE_LOOK_SCENE_DESC = "纯白背景，柔和均匀的商业棚拍光线。"


# 「单镜整套 · 衣服飘入替换」固定用标准那一版(#92)的随机种子 —— 用户要求这一镜跟标准版对齐:
# 同一套输入 + 同一个种子,成片才有可比性。
# 不写死的话,种子是按「9000 + 项目号*100 + 镜号」现推的(见 pipeline 里 build_workflow 的入参),
# 每建一个项目就换一个:#92 推出来是 18201,新建的项目会跑到 19xxx,跟标准版根本没法比。
# 后来用户挑中了 639795015 那一版(15 秒、飘动 + 换装顺序都对),就改成这个定稿种子 ——
# 这样页面上每一次生成出来的都是同一条片子。
WHOLE_LOOK_SEED = 639795015


# 「这一镜要换的那一件」在动作文案里的写法。鞋的文案是「一整双完整的…(大小和她脚上那双一样)」,
# 别的件是「一件完整的…(大小和真人身上那件一样)」—— 两种都要认,否则换鞋镜会被当成
# 「没有目标件的展示镜」,状态链就断在这一镜(用户 2026-10-19 加鞋子时踩过)。
_PIECE_IN_ACTION = re.compile(
    r"一(?:件|整双|整只|整顶|整副)完整的(.+?)\(大小和[^()]{0,30}一样\)"
)


def piece_name_of(action: str | None) -> str | None:
    """换装镜的文案里「这一镜要换的那一件」叫什么。"""
    m = _PIECE_IN_ACTION.search(action or "")
    return m.group(1).strip() if m else None


# 「整件在她所在的同一个景深平面上平移过去」:不加这句时模型会让衣服**朝镜头飞**——
# 先凑到镜头前变得很大、再缩回她身上(用户报"先把衣服移到屏幕前面,然后往后")。
# 要的是纯平面平移,衣服从头到尾待在人物那个远近。
_PIECE_DEPTH = (
    "**整件在她所在的同一个景深平面上平移过去** —— "
    "绝对不许朝镜头飞过来、不许凑到镜头跟前、不许先变大再缩小、不许糊住画面、"
    "不许旋转成侧面;"
)


def _pull_piece_lines(parts: list[str], base: str) -> list[str]:
    """「扯上身」风格的内容清单(2026-10-20):**只有 1 镜** ——

    她站在画面正中不动,整套新衣服分成两簇悬在她右上方 / 左上方的空中,
    然后**像下雨一样从上往下**落到她身上(「甩掉旧衣」「打底全套展示」两镜用户已删掉)。

    行里必须留 CHANGE_MARKERS(「从画面上方落下」)→ 建项目时认成换装镜。
    """
    names = "、".join(parts)
    return [
        # 只留这一镜:两簇衣服悬在左右上角 → 像下雨一样落下来,一次整身穿好
        f"【整套·扯上身】她站在画面正中不动;整套要换的衣服({names})"
        "**分成两簇、没有人穿着、正面朝向镜头**,一簇悬在她**右上方**的空中、一簇悬在**左上方**的空中"
        "(等距排开,没有衣架 / 挂钩 / 绳子);"
        "两簇衣服**同时松开、像下雨一样从画面上方落下** —— 每一件沿竖直方向落到对应部位,"
        "有先有后,碰到身体的瞬间就穿好(硬切,没有中间态);落完之后上方两簇全部变空。",
    ]


def _static_piece_lines(parts: list[str], base: str) -> list[str]:
    """「普通·静态图」风格的内容清单(2026-10-22):**一件一镜**,每镜就是一张 FLUX3 imgedit 静态图。

    不走视频模型,所以不需要「展示镜 + 换装镜」两镜一组、也不需要尾帧锚 ——
    每件直接 imgedit 出结果。行内容只描述「这一件穿上之后她是什么样子」,
    projects.create_project_from_script 的静态分支会拿件名构造 imgedit 指令
    (「以图1为底,让她穿上图2的 X」)。
    """
    names = [str(p).strip() for p in parts if str(p).strip()]
    names.sort(key=_wear_layer)  # 贴身先穿、外套最后
    lines: list[str] = []
    for i, name in enumerate(names):
        worn = names[: i + 1]
        lines.append(
            f"【{name}·静态换装】"
            f"她穿着{('、'.join(worn))},站在纯白背景前、全身正对镜头;"
            f"这一镜只产出一张静态图 —— 脸 / 发型 / 身材 / 姿势 / 背景全程不变,"
            f"只把「{name}」这件穿到她身上。"
        )
    return lines


def _float_piece_lines(
    parts: list[str], base: str, slots: list[str] | None = None
) -> list[str]:
    """「每件一镜」的内容清单:一件一行 + 最后 1 镜展示。

    **每镜只写「这一件该干什么」** —— 别的部位、别的件一律不写。
    (以前这里把「机位 / 站姿 / 木偶静止 / 影子 / 整套关系」那一大套整段搬进每一行,
    那是「一镜换整套」才需要的东西;按件拆之后每镜只换一件,塞进去只会把真正的指令淹没。)

    换装动作:新件从画外**快速飞入** → 从她身前扫过、**短暂遮挡**要换的部位 →
    **扫过之后干净替换**(直接是穿好的样子,没有过渡帧)。
    小件佩戴配饰(墨镜 / 项链 / 帽…)不单独排镜:直接当「一直都在身上」。
    动作里必须保留 CHANGE_MARKERS 里的词(「从画面上方落下」/「横向进来」)——
    script_split / pipeline 靠它们认这是「换装镜 + 全身镜」。

    slots:和 parts 一一对应的「部位」(读图给的),用来定穿戴顺序和"顶掉谁"——
    没有就退回按件名里的字猜。
    """
    all_names = [str(p).strip() for p in parts if str(p).strip()]
    all_slots = [str(s).strip() for s in (slots or [])]
    slot_of = {nm: all_slots[i] for i, nm in enumerate(all_names) if i < len(all_slots)}

    def _slot(nm: str) -> str:
        return slot_of.get(str(nm).strip(), "")

    # 鞋不再算「一直戴着、不单独排镜」的小件(用户 2026-10-19):它要单独排换装镜。
    always_on = [
        n
        for n in all_names
        if is_worn_accessory(n) and not _piece_carried(n) and not _is_shoe(n)
    ]
    names = [n for n in all_names if n not in always_on]
    names.sort(key=lambda n: _wear_layer(n, _slot(n)))  # 贴身先穿、外套最后
    worn_txt = ("、还戴着" + "、".join(always_on)) if always_on else ""
    # 「打底 / 旧件」的件名列表:用来给每一件找到**能顶掉的那件旧件**(换掉的是它)。
    base_names = [b.strip() for b in re.split(r"[+、,，/]", base or "") if b.strip()]
    used_old: set[str] = set()  # 一件旧件只能被顶掉一次(见 _olds_for)

    def _olds_for(name: str) -> list[str]:
        """这一件穿上之后,打底里**哪几件**会消失。

        可以不止一件:整身(连衣裙 / 连体衣)一件盖住上下半身,打底的上装和裤 / 裙**都得消失**
        (实测漏过:只顶掉睡裤,状态展示镜写成"睡衣上衣 + 连衣裙")。
        配不到就不是"替换"而是**加穿**(典型:打底长袖衫 + 开衫)—— 这时返回空列表,
        后面一律走加穿文案,绝不能写"原来那件消失":模型会自己找一件来让它消失。
        """
        want = _displaced_groups(name, _slot(name))
        out: list[str] = []
        for b in base_names:
            if b in used_old:
                continue
            if _replace_group(b, "") in want:
                used_old.add(b)
                out.append(b)
        return out

    def _change_tail(name: str, part: str, olds: list[str]) -> str:
        """「贴上之前 / 之后」那两句。"""
        if len(olds) == 1:
            old = olds[0]
            return (
                f"**它贴上之前,她{part}上还是完整的「{old}」;它吸着穿好之后,"
                f"她{part}上只剩这件{name},原来那件从画面里彻底没有"
                f"(不是同时替换、不许淡出 / 变透明 / 留半透明的旧件);"
            )
        if olds:
            t = "、".join(f"「{b}」" for b in olds)
            return (
                f"**它贴上之前,她身上还是完整的{t};它吸着穿好之后,"
                f"{t}从画面里彻底没有、她身上只剩这件{name}"
                f"(不是同时替换、不许淡出 / 变透明 / 留半透明的旧件);"
            )
        return (
            "**它贴上之前她身上穿着的是完整的原来那几件(不透明、看得见);"
            f"它吸着穿好之后,是**在她身上原来那几件的外面多穿了一件{name}** —— "
            "原来那几件一件都没消失、也没变样,更没有被这件顶掉"
            "(绝不许脱掉 / 藏起来 / 变透明);"
        )

    lines: list[str] = []
    # **开场状态镜**:最先一镜只做「她已经穿着打底」的静态展示(睡衣上衣 + 睡裤)。
    # 后面每一镜都会自动把**上一镜的末帧**当参考图 + 首帧硬锚(pipeline 的既有逻辑),
    # 所以她一路都是穿着这套衣服往下换的 —— 不用给旧件绑商品图(绑了它会被当成要飞的衣服)。
    if base_names:
        # 常驻配饰(墨镜 / 拖鞋…)也在这一镜就戴上 —— 用户要求「墨镜全程佩戴」,
        # 开场状态镜是第一镜,漏了它后面几镜(靠上一镜末帧延续)就一路都没有。
        acc_txt = ("、**还戴着" + "、".join(always_on) + "**") if always_on else ""
        lines.append(
            # 行首的 【名】 是**机器起的分镜名字**(script_split 会把它当成 title,并把这一段
            # 从正文里剥掉)。以前名字全靠模型给 —— 模型偶尔抽风退到规则兜底,名字就变成
            # 「正文前 12 个字」这种碎句(用户报「镜头名字都有问题了」)。写在这里的是确定值,
            # 不依赖模型。
            f"【打底全套展示】"
            f"全景固定机位、固定全身构图(她从头到脚完整入画、水平居中站定、双脚钉在同一个点不动)。"
            f"她**已经把这套衣服完整穿在身上({'、'.join(base_names)})**"
            f"{acc_txt} —— 上装、下装都在,"
            f"**不许赤腿、不许只穿上衣、不许露出打底 / 内衣**;"
            f"躯干和双腿保持站定(双脚钉在同一个点)、呼吸自然轻微、偶尔自然眨眼、"
            f"双臂自然垂在身侧、目光直视镜头;"
            f"**这一镜只做展示** —— 不走动、不转身、不换装、不抬手、不换衣服;"
            f"纯白背景、柔和均匀棚拍光线。"
        )
    for i, name in enumerate(names):
        worn = names[:i]
        part = _piece_part(name)
        olds = _olds_for(name)
        old = olds[0] if len(olds) == 1 else ""
        # 这一镜开始时她身上的状态 = 「打底里没被前面几件顶掉的那些」+「前面几镜已经换上的」。
        # 按**替换组**过滤(不是部位):外套不顶掉打底的上装,整身一件顶掉上装 + 下装两组。
        gone = (
            set().union(*[_displaced_groups(w, _slot(w)) for w in worn])
            if worn
            else set()
        )
        start_names = [
            b for b in base_names if _replace_group(b, "") not in gone
        ] + worn
        already = (
            f"她开始时穿着{('、'.join(start_names))}{worn_txt};"
            if start_names
            else f"她开始时穿着{base}{worn_txt};"
        )
        # 开场状态必须**完整穿好**(用户需求:默认就是穿着睡衣上衣 + 睡裤)。
        # 旧件不绑商品图、只在文字里说明,所以这里要把"已经穿在身上"钉死 ——
        # 实测否则会出现"只穿上衣、赤腿 / 露打底",或者旧件跟着新件一起飘。
        already += (
            "**画面第 1 帧她就已经把这套衣服完整穿在身上了(上装、下装都在)——"
            "不许赤腿、不许只穿上衣、不许露出打底 / 内衣,也不许把其中任何一件"
            "拿在手里或让它飘在空中。**"
        )
        # **状态展示镜**:紧挨在换装镜前面,先拍一镜「这一件换上之后她站着的样子」。
        # 它的末帧会被落成一张「状态图」,既当换装镜的**尾帧硬锚**(模型照着这张图把衣服
        # 穿好 —— 这就是「衣服穿不上 / 停在身前」的通用解法),也当下一镜的起手参考。
        # 所以在成片里它是"先看结果、再看怎么换过来的"。展示镜不写换装动作(只展示)。
        # 状态名 = 打底里**还没被顶掉**的那些 + 到这一件为止已经换上的(这一件是换完之后的
        # 状态,所以它自己也要算进去)。写错了模型会照着多穿一件(实测列出「睡裤、短裙」两件下装)。
        gone2 = gone | _displaced_groups(name, _slot(name))
        state_names = (
            [b for b in base_names if _replace_group(b, "") not in gone2]
            + worn
            + [name]
        )
        # 鞋的展示镜要把**新鞋本身**说死(它是这一镜的重点,不是"顺带穿着"):
        _shoe_line = ""
        if _is_shoe(name):
            _shoe_line = (
                f"**她双脚上穿着这一双「{name}」—— 鞋型、鞋头、颜色、材质都和参考图"
                "那双一模一样,两只脚各穿一只、整双都在、鞋头朝前、左右成对;"
                "脚上展示的必须是这一双新鞋,不许还是旧鞋**;"
            )
        lines.append(
            f"【{name}·穿好展示】"
            f"全景固定机位、固定全身构图(她从头到脚完整入画、水平居中站定、双脚钉在同一个点不动)。"
            f"她**已经把这套衣服完整穿在身上({'、'.join(state_names)})**{worn_txt} —— "
            f"上装、下装都在,**不许赤腿、不许只穿上衣、不许露出打底 / 内衣**;"
            + _shoe_line
            + f"躯干和双腿保持站定(双脚钉在同一个点)、呼吸自然轻微、偶尔自然眨眼、"
            f"双臂自然下垂并保持微张(手掌离胯约10厘米、掌心朝向身体、手指并拢、指节有轻微自然的弯曲、"
            f"手臂与躯干之间留出明显缝隙)、目光直视镜头;"
            f"**这一镜只做展示** —— 不走动、不转身、不换装、不抬手、不换衣服;"
            f"纯白背景、柔和均匀棚拍光线。"
        )
        bottom = any(k in name for k in ("裤", "裙"))
        side = "左" if i % 2 == 0 else "右"
        if _piece_carried(name):
            short, detail = _carry_mode(name)
            motion = (
                f"一件完整的{name}(大小和真人身上那件一样)从画面**{_CARRY_HAND_SIDE}侧**的画外"
                f"**整件平飞过来**,**准确地落进她伸出的{_CARRY_HAND}里,她接住后把它{short}({detail})**;"
                f"它是「{short}」,不是穿到身上、也不要盖住她的身体;不许掉在地上、不许只在她身边飘着。"
            )
        elif _is_shoe(name):
            # 鞋:一双从画面**正下方**平移进来(脚在前面那一侧),不能从画面上角扔过来。
            motion = (
                f"一整双完整的{name}(大小和她脚上那双一样)**从画面正下方平移进来、朝她的{part}移过去** —— "
                f"**始终正面朝上、鞋头朝前、左右两只成对不分开、不翻转**;"
                f"它**从她身前经过、短暂遮挡**她的{part};"
                f"碰到她{part}时**像被吸住一样直接穿好、一次到位**(两只脚各穿一只、鞋跟对脚跟);"
                + _change_tail(name, part, olds)
                + f"她全程不抬脚、不挪步。"
            )
        elif bottom:
            motion = (
                f"一件完整的{name}(大小和真人身上那件一样)**从画面{side}侧横向进来、罩到她腿上** —— "
                f"它是被**快速**扫进来的(约 0.3~0.4 秒,不许慢慢演、不许停在半空),"
                f"{_PIECE_DEPTH}"
                f"裤腰(裙腰)那一头在前,横着扫过时布料自然摆动、拖出褶皱;"
                f"它**从她身前经过、短暂遮挡**她的{part};"
                f"扫到她{part}时**像被吸住一样贴上去、顺势吸着穿好、一次贴合到位**;"
                + _change_tail(name, part, olds)
                + f"{_bottom_shape(name)}她全程不抬脚、不挪步。"
            )
        else:
            motion = (
                f"一件完整的{name}(大小和真人身上那件一样)**从画面{side}上方斜着平飞过来、罩向她上半身** —— "
                f"它带速度沿斜向轨迹飞过来(约 0.3~0.4 秒,不许停在半空、不许慢慢飘),"
                f"{_PIECE_DEPTH}"
                f"飞行时在空中轻微摆动、带布料褶皱;它**从她身前经过、短暂遮挡**她的{part};"
                f"扫到她{part}时**像被吸住一样贴上去、顺势吸着穿好、一次贴合到位**;"
                + _change_tail(name, part, olds)
            )
        # 头部:说清「换掉谁」,并**锁死旧件必须消失**(以前只写"这一镜只换X这一件"+"
        # 不许把已经穿好的脱掉",模型理解成"加一件、别脱裤子" → 换完裤子还留在身上)。
        if len(olds) == 1:
            swap = (
                f"**这一镜要把她{part}上原来那件「{old}」换成「{name}」**:"
                f"换完之后她{part}上**只穿这一件「{name}」** ——「{old}」必须从画面里**彻底没有**"
                f"(绝不许两件并存、绝不许把「{name}」套在「{old}」外面、也绝不许还留着"
                f"「{old}」的裤腿 / 裙摆 / 下摆 / 边)。"
            )
            keep = "**其它部位保持原样(不许换回打底)**。"
        elif olds:
            # 一件顶掉两件:整身(连衣裙 / 连体衣)穿上之后,打底的上装和裤 / 裙都要消失
            t = "、".join(f"「{b}」" for b in olds)
            swap = (
                f"**这一镜要把她身上原来那几件{t}换成「{name}」** —— "
                f"「{name}」是**一整件**,穿上之后{t}**都要从画面里彻底没有**"
                f"(绝不许把「{name}」套在它们外面、也绝不许还留着它们的领口 / 袖子 / 裤腿 / 下摆)。"
            )
            keep = "**其它部位保持原样(不许换回打底)**。"
        else:
            swap = f"**这一镜给她换上「{name}」**(是穿到对应部位上,不是拿在手里 / 搭在身上):"
            keep = "**其它部位保持原样(不许换回打底、也不许把已经穿好的脱掉)**。"
        # 第一次换装:手臂从身侧向外张开一次(锚图就是"打底展示",手臂还在身侧);
        # 后面每一镜的锚图已经带着微张姿势,只需要保持。
        _arm_open = (
            "开始时双臂自然垂在身侧;这件衣服整件贴好之后,双臂从身侧向外张开到"
            "微张位置,然后保持;"
            if not worn
            else ""
        )
        lines.append(
            f"【{name}·飞入换装】"
            f"全景固定机位、固定全身构图(她从头到脚完整入画、水平居中站定、双脚钉在同一个点不动)。"
            f"{swap}{already} {keep}{motion}"
            f"**躯干和双腿全程静止;{_arm_open}双臂保持微张的固定姿势"
            f"(手掌离胯约10厘米、掌心朝向身体、手指并拢、指节有轻微自然的弯曲、手臂与躯干之间留出明显缝隙;不抬手去接、不伸手去拉衣服);"
            f"**画面里只有她自己的两条手臂,衣服的袖子是空布料,绝不许再长出多余的手 / 手臂**;"
            f"**不要照搬人物参考图里她身上的配件(包 / 鞋 / 帽子 / 首饰)**;"
            f"衣服经过时在她身上和地面留一层淡淡的影子;"
            f"**不要出现产品图 / 平铺图 / 衣架挂钩 / 分格 / 第二层背景**;纯白背景、柔和均匀棚拍光线。"
        )
    # 结尾**不再单独加一镜「整套展示」** —— 每件前面已经有一镜状态展示,最后一镜换完之后
    # 画面里就是整套(换装镜的尾帧锚就是那套的展示图)。多出来的一镜是重复的。
    return lines


