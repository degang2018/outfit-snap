# ---------------- 「一镜穿完整套」的时间轴 ----------------
# 实测(项目 86 / 56 帧):一镜要塞三件顺序换装时,模型根本排不开 —— 它会把三件
# 在同一瞬间一起涌进画面、糊成一团(0.75 秒就给完),长裤还中途摊成开叉长裙。
# 提示词里"一次只来一件"这类话压不住,必须**给它一份写明每件几秒进的节拍表**,
# 并且把这一镜的时长按件数放大(件数越多越长),它才有地方把顺序排开。
FLOAT_EVENT_ACTION_SECONDS = 2.0  # 每件「进场 → 落下 → 穿好」这一拍占多久
FLOAT_EVENT_GAP_SECONDS = 1.0  # 一件做完后等她站稳、画面安静这么久,下一件才开始
FLOAT_TAIL_SECONDS = 0.7  # 全部穿完之后留一点展示时间
FLOAT_MAX_FRAMES = 362  # H3 单次生成的上限(必须仍是 17k+5)


def change_events(
    names, slots: dict[str, str] | None = None, keep_shoes: bool = False
) -> list[str]:
    """本镜头要「一件件发生」的换装事件清单,按穿戴顺序排好。

    通用的地方:**件数不限** —— 三件套装、多加一件外套、再加一个背包,都是同一套写法。
    一直在身上的小件配饰(墨镜 / 项链 / 帽…)不算事件:它们从第 1 镜就戴着,
    没有"进场"这回事。包(背包 / 手提包…)算事件,动作是"飞到手里 / 背上"。
    **鞋也是一件** —— 按件排镜时它要单独排一镜换装(旧拖鞋 → 新鞋);只有 non-piece
    (一镜穿整套)才把常驻配饰栏里的鞋当成"一直戴着"。

    slots:件名 -> 读图给的「部位」(有就优先按它排层,见 _wear_layer)。
    keep_shoes:鞋算不算事件(按件排镜传 True;见上面那条)。
    """
    out = [str(n).strip() for n in (names or []) if str(n).strip()]
    out = [
        n
        for n in out
        if _piece_carried(n) or (keep_shoes and _is_shoe(n)) or not is_worn_accessory(n)
    ]
    smap = slots or {}
    out.sort(key=lambda n: _wear_layer(n, smap.get(n, "")))
    return list(dict.fromkeys(out))


def float_shot_frames(events: int, fps: int) -> int:
    """按「有几件事件」算出这一镜要拍多少帧(必须落在 17k+5 上)。

    一件事件 = 进场本身 + 事后停顿,所以件数越多、这一镜越长。这就是"一镜穿完整套"
    以前会在 0.75 秒内把几件一起糊上来的根因 —— 时间根本不够排顺序。
    """
    n = max(1, int(events))
    seconds = (
        n * (FLOAT_EVENT_ACTION_SECONDS + FLOAT_EVENT_GAP_SECONDS) + FLOAT_TAIL_SECONDS
    )
    want = int(round(seconds * fps))
    k = max(1, -(-(want - 5) // 17))  # 向上取到最近的 17k+5
    return min(FLOAT_MAX_FRAMES, 17 * k + 5)


def _event_arrival(name: str) -> str:
    """这件是「怎么进场的」—— 用来写时间轴里每一拍的动作。"""
    if _piece_carried(name):
        short, _ = _carry_mode(name)
        return f"从画面的画外飞过来、落进她手里,她接住之后把它{short}"
    if _is_shoe(name):
        # 鞋从**正下方**进来(脚在前面那一侧),不能从肩膀 / 头顶高度落下来。
        return "从画面正下方整双平移进来、朝她的双脚移过去,碰到双脚时整双穿好"
    if any(k in name for k in ("裤", "裙")):
        return "从画面的一侧横着扫进来,罩到她腿上、穿好"
    if is_worn_accessory(name):
        return f"从画面上方落下来,戴到她的{_piece_part(name)}"
    return "从画面上方落下来、盖住她的上身、穿好"


def float_timeline_text(events: list[str], frames: int, fps: int) -> str:
    """把「这一镜要发生的事件」逐条列成时间轴 —— 几件就列几拍,一件一拍、拍间停 1 秒。

    通用:件数变了,拍数和总时长跟着变(见 float_shot_frames),文案不用改。
    """
    n = len(events)
    if n <= 0:
        return ""
    secs = frames / fps
    per = FLOAT_EVENT_ACTION_SECONDS + FLOAT_EVENT_GAP_SECONDS
    beats: list[str] = []
    for i, name in enumerate(events):
        t0 = i * per
        t1 = t0 + FLOAT_EVENT_ACTION_SECONDS
        beats.append(
            f"**第 {i + 1} 拍(大约 {t0:g}~{t1:g} 秒):只有「{name}」{_event_arrival(name)} —— "
            f"这一拍里画面上只许出现这一件,别的件一件都不许出现**;"
            f"**这一件是「一落到底就已经穿在她身上」:它在这一拍里完成"
            f"「进画面 → 落下 → 穿好」,这一拍结束时它必须已经整件穿在她身上了;"
            f"绝对不许出现「一整件完整的衣服悬在半空 / 悬在她旁边 / 悬在她身前」的帧;**"
            f"**落定之后它就已经整件穿在她身上了 —— 接下来大约 {FLOAT_EVENT_GAP_SECONDS:g} 秒是「空档」:"
            f"画面上只有她一个人站在原处(继续呼吸、头轻轻偏一点、手指松一下、腰胯轻摆),"
            f"画面里绝对不许有任何衣服 —— 不许衣服悬在半空、悬在她旁边、挡在她脸前或身上,"
            f"连一角衣料、一条袖子都不许出现;这一件已经穿在她身上了,不是还飘在空中;"
            f"等这 {FLOAT_EVENT_GAP_SECONDS:g} 秒过去,下一件才开始进场**;"
        )
    return (
        f"**这一镜一共要发生 {n} 件事(就是要换上的 {n} 件),必须严格按下面的时间轴分 {n} 拍、"
        f"一件一拍地演(整镜大约 {secs:.1f} 秒);绝对不许把几件挤在同一拍里,"
        f"也绝对不许漏掉其中任何一件**:"
        + "".join(beats)
        + "**每拍之间的空档里,画面上只有她一个人、没有任何衣服 —— 这是这一镜最重要的铁律:**"
        "**衣服只许在「进场那一瞬」出现(而且是从画面上沿裁着进来、一落到底就穿好),"
        "绝不许一整件完整地悬在空中等**;"
        "**所有件都穿好之后:画面上不再有任何衣服在飞、在飘、在悬着;"
        "但她照样继续一直在动 —— 呼吸起伏、头轻轻偏一点、手指松一下、腰胯轻摆,"
        "绝对不许变成静止定帧**;"
        "**核心:同一时刻画面上只允许出现「一件」正在进场的衣服 —— 绝对不许两件、"
        "更不许三件一起涌进画面,绝对不许在镜头开头一下子把几件全甩上来、糊成一团**;"
    )


