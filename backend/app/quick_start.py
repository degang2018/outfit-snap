def _slot_of(d: dict) -> str:
    """取读图给的「部位」(件字典上的 `slot`)。"""
    return str((d or {}).get("slot") or "").strip()


# 拆件名的分隔符:「同一前缀 + 破折号 + 单件名」(见 script_split 的拆件约定)。
_PIECE_SEP = ("-", "－", "—", "–", "·")


def _strip_piece_prefix(name: str) -> str:
    """「套装-高腰百褶短裙」-> 「高腰百褶短裙」。

    拆件名里的前缀说的是"这是哪一套",不是这一件的样子 —— 拿整名去扫关键词会被
    「套装 / 套装裙」这类词带偏(和 piece_prompt 里的同一份逻辑)。
    """
    n = str(name or "")
    for sep in _PIECE_SEP:
        head, s, tail = n.rpartition(sep)
        if s and head and tail.strip():
            return tail.strip()
    return n


def _part_group(name: str, slot: str = "") -> str:
    place, _ = parse_slot(slot)
    g = place_group(place)
    if g != "other":
        return g
    n = _strip_piece_prefix(name)
    for group, keys in _GROUP_HINTS:
        if any(k in n for k in keys):
            return group
    return "other"


# ---------------------------------------------------------------- 「它和谁互相替换」
# `_part_group` 回答"穿在身体哪个部位"(进场高度按它),但「上身」把上衣和外套压成同一档 ——
