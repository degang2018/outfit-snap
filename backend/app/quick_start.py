def _picked_detail_lines(
    picked_shots: list[str] | None,
    actions: list[str],
    shot_map: dict[str, str] | None,
    label_map: dict[str, str] | None = None,
) -> list[str]:
    """把「勾选的细节镜 + 用户自定义动作」翻成内容清单里的几行。

    两处用到:①纯勾选模式(招牌镜 + 这些细节镜);②「按件排镜」合排时插在换装和展示镜之间。
    """
    if picked_shots is None and not actions:
        return []
    by_key = {it["key"]: it["action"] for it in SHOT_LIBRARY_ALL}
    labels = {it["key"]: (it.get("label") or "") for it in SHOT_LIBRARY_ALL}
    if shot_map:
        by_key.update(shot_map)
    if label_map:
        labels.update(label_map)
    picked = [str(k).strip() for k in (picked_shots or []) if str(k).strip()]

    # 行首带上 【镜头名】:名字来自镜头库的 label(确定性),别让模型起名(见上面说明)。
    # 自定义分镜(my_N)也要带 —— 以前 labels 只查内置库,自定义的行没有 【名】,标题靠模型起,
    # 模型一旦把 i 数错一位,标题就整体错位一格(实测项目 212/213/214:摸狗的标题配了杂志的正文)。
    #
    # **动作正文里的换行必须压成空格**:内容清单是「一行一镜」,analyze_script 按 \n 切行;
    # 自定义分镜从生成结果里存下来时常常带两段(如「整套展示」正文末尾那行"她全程戴着墨镜…"),
    # 中间的 \n 会被切成**单独一镜**,于是同一行变成两个镜头(实测项目 250:s25/s26 两个「扶墨镜近景」)。
    def _one_line(s: str) -> str:
        return re.sub(r"\s*\n+\s*", " ", str(s or "")).strip()

    out = []
    for k in picked:
        act = _one_line(by_key.get(k, k))
        lab = labels.get(k) or ""
        out.append(f"【{lab}】{act}" if lab else act)
    return out + [_one_line(a) for a in actions]


def draft_script(
    *,
    garment: str,
    scene_desc: str,
    style: str = "",
    props: list[str] | None = None,
    shot_count: int = 8,
    total_seconds: float = 30.0,
    extra: str = "",
    float_mode: bool = False,
    float_variant: str = "overhead",
    base_outfit: str = "",
    custom_actions: list[str] | None = None,
    picked_shots: list[str] | None = None,
    shot_map: dict[str, str] | None = None,
    label_map: dict[str, str] | None = None,
    parts: list[str] | None = None,
    part_kinds: list[str] | None = None,
    piece_style: str = "",
) -> tuple[dict | None, str, str]:
    """把(服装 + 空间 + 调性 + 道具 + 时长/镜头数)写成一份剧本。

    float_mode=True 走悬浮变装(结构由 float_variant 决定):
      overhead —— 衣服从手里托举到头顶悬浮,再落下穿好;
      side     —— 衣服凭空一件件直接吸到她身上,自动穿好;
      piece    —— 每件一镜:一镜只演"这一件平移进来挡住部位",换装藏在硬切之间
                  (件数由 parts 决定;N 件就给 N+1 镜)。
    base_outfit 是招牌镜里她穿的打底(留空用 DEFAULT_BASE_OUTFIT);
    picked_shots 是用户从镜头库里**勾选**的细节镜头 key —— **传了它(哪怕是空列表)就不再让模型编内容**,
    直接按「招牌镜 + 勾选的镜头 + custom_actions」拼出内容清单。
    shot_map 是 key -> action 的查表(合并了用户自己加的镜头),不传就只用内置库。
    parts 是「按件排镜」用的一件件衣服名(通常来自读图认件),件数不限(4 件、5 件都行);
    part_kinds 和它一一对应的「部位」(读图给的),有就按它定穿戴顺序 / 谁顶掉谁,没有就退回按件名猜。
    """
    per = total_seconds / max(1, shot_count)
    props = [p for p in (props or []) if p and p.strip()]
    side = float_mode and float_variant == "side"
    base = (base_outfit or "").strip() or DEFAULT_BASE_OUTFIT
    actions = [a.strip() for a in (custom_actions or []) if a and a.strip()]

    # 「按件排镜」:件数由用户上传的衣服决定,直接拼内容清单 —— 不让模型编,免得它少排/多排镜头。
    # 用户勾的细节镜(和自己写的动作)插在「换装」和最后的「展示镜」之间:
    # 「按件排镜」本来只演换装,合在一起才是一条完整的片子(换装一件一镜 + 细节镜 + 展示)。
    piece_names = [str(p).strip() for p in (parts or []) if str(p).strip()]
    if float_mode and float_variant == "piece" and piece_names:
        _style = (piece_style or "").strip().lower()
        _is_pull = _style == "pull"
        _is_static = _style == "static"
        if _is_pull:
            # 「扯上身」= 开场扯掉 + 一镜穿整套(2 镜),不是一件一镜。
            piece_lines = _pull_piece_lines(piece_names, base)
        elif _is_static:
            # 「普通·静态图」= 一件一镜,每镜一张 FLUX3 imgedit PNG。
            piece_lines = _static_piece_lines(piece_names, base)
        else:
            piece_lines = _float_piece_lines(piece_names, base, part_kinds)
        detail = _picked_detail_lines(picked_shots, actions, shot_map, label_map)
        # 清单已经是「展示(打底) → [展示(这件换好) → 换装(这件)] × 件数」,细节镜直接接在后面。
        lines = piece_lines + detail
        n_piece = len(piece_names)
        worn = [
            n
            for n in piece_names
            if is_worn_accessory(n) and not _piece_carried(n) and not _is_shoe(n)
        ]
        _static_hint = (
            f"按你上传的 {len(piece_names)} 件衣服排了 {n_piece} 个静态换装镜"
            "(每件一张 FLUX3 静态图,最后输出单张成片图)"
        )
        return (
            {
                "title": f"悬浮变装 · 按件排镜 {len(lines)} 镜",
                "script": "\n".join(lines),
                # **镜头数以清单为准**:清单里除了用户第 3 栏那几件,还可能有"携带件"(包 / 围裙…)
                # 是从配饰栏进来的 —— 前端自己按件数估的镜数会偏小,拿它去排分镜就会截断尾巴。
                "shot_count": len(lines),
            },
            "compose",
            (
                f"按你上传的 {len(piece_names)} 件衣服排了 1 镜"
                "(整套衣服悬在右上方,她张开双臂 —— **一次全部吸上身**)"
                if _is_pull
                else _static_hint
                if _is_static
                else f"按你上传的 {len(piece_names)} 件衣服排了 {n_piece} 个换装镜"
                + f"(每件前各 1 镜「换好之后的样子」展示,用来给换装镜当尾帧锚,共 {n_piece} 镜)"
            )
            + (f" + {len(detail)} 个细节镜" if detail else "")
            + (f"(小件配饰 {'、'.join(worn)} 不单独排镜,全程一直戴着)" if worn else ""),
        )

    # 勾选镜头模式:内容完全由用户决定,模型只会在后面负责排分镜,不碰内容
    if float_mode and picked_shots is not None:
        detail = _picked_detail_lines(picked_shots, actions, shot_map, label_map)
        lines = [_float_opening_line(side, base)] + detail
        return (
            {"title": f"悬浮变装 · {len(lines)} 镜", "script": "\n".join(lines)},
            "compose",
            f"按你勾选的 {len(detail)} 个细节镜头直接拼出内容清单(没有让模型编内容)",
        )

    if float_mode:
        scene_line = "空旷的纯白影棚:纯白背景墙 + 浅灰地面,没有任何家具或陈设"
        style_line = (
            "悬浮变装 · 侧面飞入 —— 纯白棚、衣服一件件凭空直接吸到她身上自动穿好、全程零运镜硬切"
            if side
            else "悬浮变装 —— 纯白棚、衣服自己悬浮并自动穿到身上、全程零运镜硬切"
        )
    else:
        scene_line = scene_desc
        style_line = style or "自然、干净"
    user = (
        f"服装:{garment}\n"
        f"拍摄空间:{scene_line}\n"
        f"整体调性:{style_line}\n"
        f"可用道具与身体动作:{'、'.join(props) if props else '不使用额外道具'}\n"
        f"镜头数量:恰好 {shot_count} 个;总时长 {total_seconds:g} 秒,每个镜头约 {per:.1f} 秒。\n"
    )
    if float_mode:
        user += (
            "补充:要展示的这套服装在剧本里一律称它为「套装」(稍后会给它单独指定一张服装参考图)。"
            f"开场人物穿的是{base}。"
        )
        user += (
            "她开场**空着手**,「套装」还在画面之外,是**从画外飞进来**的。\n"
            if side
            else "她开场**双手捧着「套装」**。\n"
        )
    if actions:
        user += "用户指定的细节动作(必须逐条用上):" + ";".join(actions) + "\n"
    if extra.strip():
        user += f"用户补充要求:{extra.strip()}\n"
    if float_mode:
        user += f"\n请输出 JSON:片名 + 剧本正文(恰好 {shot_count} 段动作,**不要单独写设定段**)。"
    else:
        user += f"\n请输出 JSON:片名 + 剧本正文(1 段设定 + {shot_count} 段动作)。"

    if float_mode:
        system = FLOAT_SIDE_SCRIPT_SYSTEM if side else FLOAT_SCRIPT_SYSTEM
        system = system.replace("__BASE__", base).replace("__IDEAS__", _library_ideas())
        if actions:
            system += (
                "\n【用户指定的细节动作】下面这些动作**必须逐条用上,一条对应一个细节镜**"
                "(顺序可以按节奏调整),并给每条安排合适的景别和道具:\n"
                + "\n".join(f"- {a}" for a in actions)
                + "\n"
            )
    else:
        system = SCRIPT_SYSTEM
    try:
        data = llm.chat_json(system, user, temperature=0.6)
    except Exception as exc:  # noqa: BLE001
        return None, "llm", f"调用模型失败:{str(exc)[:200]}"
    if not data:
        return None, "llm", "模型没有返回可用的剧本"

    script = str(data.get("script") or "").strip()
    if not script:
        return None, "llm", "模型返回的剧本是空的"
    title = (str(data.get("title") or "").strip() or "未命名短片")[:40]
    return {"title": title, "script": script}, "llm", settings.llm_model
