        nm = names[i]
        part = _piece_part(nm)
        grp = _part_group(nm, slots[i])
        spot = _entry_spot(grp, k)
        # 这一件要顶掉的那件「旧件」:从起始套装(_base)里找**同一替换组、且还没被用掉**的那件。
        # 实测**点名具体件名**(裙配睡裤、上衣配睡衣上衣)比泛指"这个部位原来那件"有效得多。
        # 用**替换组**而不是部位:外套只跟外套互换 —— 打底长袖衫 + 开衫是「加穿」,
        # 写成"把长袖衫换成开衫"模型会把里面的长袖衫脱掉(实测)。
