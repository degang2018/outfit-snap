SHOT_LIBRARY_ALL: list[dict] = SHOT_LIBRARY + EXTRA_SHOT_LIBRARY


def _strip_detail_prefix(action: str) -> str:
    for p in _DETAIL_PREFIXES:
        if action.startswith(p):
            return action[len(p) :]
    return action


def _library_ideas() -> str:
    """把镜头库拼成剧本规则里的 ①~⑳ 列表(去掉那句"已经穿好完整套装"前缀,规则里已另有交代)。"""
    items = SHOT_LIBRARY[: len(_IDEA_NUMS)]
    parts = [
        f"{_IDEA_NUMS[i]}{_strip_detail_prefix(it['action'])};"
        for i, it in enumerate(items)
    ]
    if parts:
        parts[-1] = parts[-1][:-1] + "。"
    return "".join(parts)


def build_shot_library(
    overrides: dict[str, dict] | None = None, customs: list[dict] | None = None
) -> tuple[list[dict], list[dict]]:
    """把内置镜头 + 用户自己的改动合成两样东西。

    library —— 勾选区用的列表(被删掉的已剔除,改过文案的用改后的);
    items   —— 「管理细节镜头」面板用的列表(含被删掉的,方便恢复)。

    overrides: {内置 key: {"label","action","hidden"}};customs: [{"id","key","label","action"}]
    """
    overrides = overrides or {}
    library: list[dict] = []
    items: list[dict] = []
    for it in list(SHOT_LIBRARY) + list(EXTRA_SHOT_LIBRARY):
        o = overrides.get(it["key"]) or {}
        label = (o.get("label") or "").strip() or it["label"]
        action = (o.get("action") or "").strip() or it["action"]
        hidden = bool(o.get("hidden"))
        edited = bool((o.get("label") or "").strip() or (o.get("action") or "").strip())
        items.append(
            {
                "kind": "builtin",
                "key": it["key"],
                "label": label,
                "action": action,
                "seconds": 3.0,
                "hidden": hidden,
                "edited": edited,
            }
        )
        if not hidden:
            library.append(
                {"key": it["key"], "label": label, "action": action,
                 "seconds": 3.0, "group": "builtin"}
            )
    for c in customs or []:
        hidden = bool(c.get("hidden"))
        _secs = float(c.get("seconds") or 3.0)
        items.append(
            {
                "kind": "custom",
                "id": c["id"],
                "key": c["key"],
                "label": c["label"],
                "action": c["action"],
                "seconds": _secs,
                "hidden": hidden,
            }
        )
        if not hidden:
            library.append(
                {
                    "key": c["key"],
                    "label": c["label"],
                    "action": c["action"],
                    "seconds": _secs,
                    "group": "custom",
                }
            )
    return library, items


