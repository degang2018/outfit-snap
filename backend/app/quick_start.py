def _piece_carried(name: str) -> bool:
    return any(k in name for k in _CARRY_HINTS)


_SHOE_HINTS = ("鞋", "靴", "拖鞋", "凉拖", "棉拖", "高跟")


def _is_shoe(name: str | None) -> bool:
    """是不是鞋 / 靴 / 拖鞋。

    鞋**不再算「一直戴着、不单独排镜」的小件**(用户 2026-10-19):新衣服里带一双新鞋时,
    要像别的件一样排「穿好展示 + 飞入换装」两镜,把打底那双旧鞋顶掉。
    """
    return any(k in _strip_piece_prefix(name or "") for k in _SHOE_HINTS)


def is_carried_piece(name: str) -> bool:
    """这一件是不是「包 / 手袋」这类拿在手上的配件(不是穿在身上的衣服)。

    建项目时用它决定:展示镜要不要额外绑这一件的商品参考图(见 routers/projects.py)。
    """
    return _piece_carried(name)


def _carry_mode(name: str) -> tuple[str, str]:
    """这一件怎么拿:(短说法, 姿势细描述)。"""
    for keys, short, detail in _CARRY_MODES:
        if any(k in name for k in keys):
            return short, detail
    return _CARRY_DEFAULT


