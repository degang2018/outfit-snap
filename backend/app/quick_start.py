def _wear_layer(name: str, slot: str = "") -> int:
    """这一件该在第几个层次穿(数字小的先穿)。"""
    place, outside = parse_slot(slot)
    if place:
        if place in ("脚", "头", "手", "配饰"):
            return _LAYER_ACC
        return _LAYER_OUTER if outside else _LAYER_BODY
    n = _strip_piece_prefix(name)
    if any(k in n for k in _ACC_HINTS):
        return _LAYER_ACC
    if any(k in n for k in _OUTER_HINTS):
        return _LAYER_OUTER
    return _LAYER_BODY


